/**
 * Admin controller for BLE token management
 * Only accessible to administrators (access_level >= 5)
 */

const db = require('../config/db');
const { success, error } = require('../utils/response');
const { createBleToken, getUserBleTokens, revokeAllUserTokens, logBleActivity } = require('../utils/bleTokenService');

/**
 * GET /api/admin/ble-tokens/status
 * View token status for all users (admin only)
 */
const getUsersTokenStatus = async (req, res, next) => {
  try {
    if (req.user.access_level < 5) {
      return error(res, 'Only administrators can access this endpoint', 403);
    }

    const { status = 'all', limit = 100, offset = 0 } = req.query;

    let query = `
      SELECT 
        u.user_id,
        u.full_name,
        u.email,
        u.department,
        u.role_id,
        COUNT(DISTINCT bt.id) as active_tokens,
        MAX(bt.created_at) as latest_token_date,
        MAX(bt.expires_at) as latest_token_expiry,
        CASE 
          WHEN COUNT(bt.id) = 0 THEN 'no_token'
          WHEN MAX(bt.expires_at) < NOW() THEN 'expired'
          WHEN MAX(bt.expires_at) < DATE_ADD(NOW(), INTERVAL 7 DAY) THEN 'expiring_soon'
          ELSE 'active'
        END as token_status
      FROM users u
      LEFT JOIN ble_tokens bt ON u.user_id = bt.user_id AND bt.is_revoked = 0
      WHERE u.status = 'ACTIVE'
    `;

    // Filter by token status
    if (status === 'no_token') {
      query += ` HAVING COUNT(bt.id) = 0`;
    } else if (status === 'expired') {
      query += ` HAVING MAX(bt.expires_at) < NOW()`;
    } else if (status === 'expiring_soon') {
      query += ` HAVING MAX(bt.expires_at) < DATE_ADD(NOW(), INTERVAL 7 DAY)`;
    }

    query += ` GROUP BY u.user_id ORDER BY u.full_name ASC LIMIT ? OFFSET ?`;

    const [users] = await db.query(query, [parseInt(limit), parseInt(offset)]);

    // Total count
    const [totalCount] = await db.query(
      `SELECT COUNT(*) as total FROM users WHERE status = 'ACTIVE'`
    );

    return success(res, {
      users,
      pagination: {
        total: totalCount[0].total,
        limit: parseInt(limit),
        offset: parseInt(offset),
        pages: Math.ceil(totalCount[0].total / parseInt(limit))
      }
    }, 'User token status retrieved');

  } catch (err) {
    next(err);
  }
};

/**
 * POST /api/admin/ble-tokens/generate/:userId
 * Manually generate BLE token for a specific user (admin only)
 */
const generateTokenForUser = async (req, res, next) => {
  try {
    if (req.user.access_level < 5) {
      return error(res, 'Only administrators can access this endpoint', 403);
    }

    const { userId } = req.params;
    const { deviceName, revokeExisting = false } = req.body;

    if (!userId) {
      return error(res, 'User ID is required', 400);
    }

    // Verify user exists
    const [users] = await db.query(
      `SELECT user_id, full_name, email FROM users WHERE user_id = ?`,
      [userId]
    );

    if (!users.length) {
      return error(res, 'User not found', 404);
    }

    const user = users[0];

    // Optionally revoke existing tokens
    if (revokeExisting) {
      await revokeAllUserTokens(userId);
    }

    // Create new token
    const token = await createBleToken(
      userId,
      deviceName || `Token for ${user.full_name}`
    );

    // Log admin action
    await logBleActivity(
      userId,
      'TOKEN_ADMIN_GENERATED',
      `Token generated by admin ${req.user.user_id}`
    );

    return success(res, {
      user: {
        id: user.user_id,
        name: user.full_name,
        email: user.email
      },
      token: {
        displayToken: token.displayToken,
        expiresAt: token.expiresAt,
        deviceName: token.deviceName
      },
      message: 'Token generated successfully'
    }, 'Token generated');

  } catch (err) {
    next(err);
  }
};

/**
 * POST /api/admin/ble-tokens/generate-batch
 * Generate tokens for multiple users at once (admin only)
 */
const generateTokensBatch = async (req, res, next) => {
  try {
    if (req.user.access_level < 5) {
      return error(res, 'Only administrators can access this endpoint', 403);
    }

    const { userIds = [], all = false, revokeExisting = false } = req.body;

    let targetUserIds = userIds;

    if (all) {
      // Get all active users without tokens
      const [users] = await db.query(`
        SELECT user_id FROM users
        WHERE status = 'ACTIVE'
          AND user_id NOT IN (
            SELECT DISTINCT user_id FROM ble_tokens WHERE is_revoked = 0
          )
        LIMIT 1000
      `);
      targetUserIds = users.map(u => u.user_id);
    }

    if (!targetUserIds.length) {
      return error(res, 'No users to process', 400);
    }

    let successCount = 0;
    let errorCount = 0;
    const results = [];

    for (const userId of targetUserIds) {
      try {
        if (revokeExisting) {
          await revokeAllUserTokens(userId);
        }

        const token = await createBleToken(userId, 'Generated Token');

        results.push({
          userId,
          status: 'success',
          expiresAt: token.expiresAt
        });
        successCount++;
      } catch (batchErr) {
        errorCount++;
        results.push({
          userId,
          status: 'failed',
          error: batchErr.message
        });
      }
    }

    // Log admin action
    await logBleActivity(
      req.user.user_id,
      'BATCH_TOKEN_GENERATION',
      `Generated tokens for ${successCount} users`
    );

    return success(res, {
      summary: {
        totalRequested: targetUserIds.length,
        successful: successCount,
        failed: errorCount
      },
      results
    }, 'Batch token generation completed');

  } catch (err) {
    next(err);
  }
};

/**
 * GET /api/admin/ble-tokens/audit-log
 * View audit log for token operations (admin only)
 */
const getTokenAuditLog = async (req, res, next) => {
  try {
    if (req.user.access_level < 5) {
      return error(res, 'Only administrators can access this endpoint', 403);
    }

    const { days = 30, limit = 100, offset = 0, action } = req.query;

    let query = `
      SELECT 
        ba.id,
        ba.user_id,
        u.full_name,
        u.email,
        ba.action,
        ba.details,
        ba.logged_at,
        ba.ip_address
      FROM ble_token_audit_log ba
      LEFT JOIN users u ON ba.user_id = u.user_id
      WHERE ba.logged_at > DATE_SUB(NOW(), INTERVAL ? DAY)
    `;

    const params = [parseInt(days)];

    if (action) {
      query += ` AND ba.action = ?`;
      params.push(action);
    }

    query += ` ORDER BY ba.logged_at DESC LIMIT ? OFFSET ?`;
    params.push(parseInt(limit), parseInt(offset));

    const [logs] = await db.query(query, params);

    // Count total
    let countQuery = `
      SELECT COUNT(*) as total FROM ble_token_audit_log
      WHERE logged_at > DATE_SUB(NOW(), INTERVAL ? DAY)
    `;
    const countParams = [parseInt(days)];

    if (action) {
      countQuery += ` AND action = ?`;
      countParams.push(action);
    }

    const [totalCount] = await db.query(countQuery, countParams);

    return success(res, {
      logs,
      pagination: {
        total: totalCount[0].total,
        limit: parseInt(limit),
        offset: parseInt(offset)
      }
    }, 'Audit log retrieved');

  } catch (err) {
    next(err);
  }
};

/**
 * GET /api/admin/ble-tokens/alerts
 * View active alerts for all users (admin only)
 */
const getTokenAlerts = async (req, res, next) => {
  try {
    if (req.user.access_level < 5) {
      return error(res, 'Only administrators can access this endpoint', 403);
    }

    const { severity, acknowledged = false, limit = 100 } = req.query;

    let query = `
      SELECT 
        ba.id,
        ba.user_id,
        u.full_name,
        u.email,
        ba.alert_type,
        ba.severity,
        ba.message,
        ba.is_acknowledged,
        ba.created_at
      FROM ble_token_alerts ba
      LEFT JOIN users u ON ba.user_id = u.user_id
      WHERE ba.is_acknowledged = ?
    `;

    const params = [acknowledged ? 1 : 0];

    if (severity) {
      query += ` AND ba.severity = ?`;
      params.push(severity);
    }

    query += ` ORDER BY FIELD(ba.severity, 'critical', 'high', 'medium', 'low'), ba.created_at DESC LIMIT ?`;
    params.push(parseInt(limit));

    const [alerts] = await db.query(query, params);

    return success(res, {
      alerts,
      count: alerts.length
    }, 'Alerts retrieved');

  } catch (err) {
    next(err);
  }
};

/**
 * POST /api/admin/ble-tokens/alerts/:alertId/acknowledge
 * Mark an alert as acknowledged (admin only)
 */
const acknowledgeAlert = async (req, res, next) => {
  try {
    if (req.user.access_level < 5) {
      return error(res, 'Only administrators can access this endpoint', 403);
    }

    const { alertId } = req.params;

    await db.query(
      `UPDATE ble_token_alerts SET is_acknowledged = 1, acknowledged_at = NOW() WHERE id = ?`,
      [alertId]
    );

    return success(res, {}, 'Alert acknowledged');

  } catch (err) {
    next(err);
  }
};

/**
 * POST /api/admin/ble-tokens/alerts/bulk-acknowledge
 * Acknowledge multiple alerts at once
 */
const acknowledgeAlertsBulk = async (req, res, next) => {
  try {
    if (req.user.access_level < 5) {
      return error(res, 'Only administrators can access this endpoint', 403);
    }

    const { alertIds = [], all = false } = req.body;

    let query = `UPDATE ble_token_alerts SET is_acknowledged = 1, acknowledged_at = NOW()`;
    const params = [];

    if (all) {
      query += ` WHERE is_acknowledged = 0`;
    } else if (alertIds.length > 0) {
      query += ` WHERE id IN (${alertIds.map(() => '?').join(',')})`;
      params.push(...alertIds);
    } else {
      return error(res, 'No alerts to acknowledge', 400);
    }

    const [result] = await db.query(query, params);

    return success(res, {
      acknowledged: result.affectedRows
    }, 'Alerts acknowledged');

  } catch (err) {
    next(err);
  }
};

module.exports = {
  getUsersTokenStatus,
  generateTokenForUser,
  generateTokensBatch,
  getTokenAuditLog,
  getTokenAlerts,
  acknowledgeAlert,
  acknowledgeAlertsBulk
};
